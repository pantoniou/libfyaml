#!/bin/sh
# SPDX-License-Identifier: MIT
#
# gen-predefs.sh [-o FILE] [-a NAME] host CC
# gen-predefs.sh [-o FILE] [-a NAME] targets CC TRIPLE...
#
# Write (the standard output by default) a C source fragment with the predefined macros of a compiler. cparse
# compiles the fragment in, so that it never has to run a compiler.
#
#   host     the macros and the system include directories of CC for its own
#            target. A second set is made for -m32 when CC accepts it and
#            changes the pointer size.
#   targets  the macros of CC (a clang, or the clang of Fil-C) for each TRIPLE,
#            with --target.
#
# The array is named cp_predef_sets_MODE; with -a it is cp_predef_sets_NAME.
#
# CC is a command; it may hold options such as -m32.
#
# Each set holds "NAME=VALUE" strings, the form of cc -D. When CC fails, the
# fragment holds no sets: cparse then uses its clang sets.
set -u

if [ "${1:-}" = -o ]; then
	exec > "${2:?usage: gen-predefs.sh -o FILE ...}"
	shift 2
fi

name=
if [ "${1:-}" = -a ]; then
	name=${2:?usage: gen-predefs.sh -a NAME ...}
	shift 2
fi

mode=${1:?usage: gen-predefs.sh host CC | targets CC TRIPLE...}
cc=${2:?usage: gen-predefs.sh host CC | targets CC TRIPLE...}
shift 2

tmp=$(mktemp -d "${TMPDIR:-/tmp}/predefs.XXXXXX") || exit 1
trap 'rm -rf "$tmp"' EXIT

# a tab; \t in the replacement of sed is not a tab for every sed (BSD)
tab=$(printf '\t')

# the strings of a "#define NAME VALUE" listing, in the form of cc -D
defines() {
	sed -n 's/^#define \([A-Za-z_0-9]*\)\(([^)]*)\)\{0,1\} \{0,1\}\(.*\)$/\1\2=\3/p' "$1" \
	    | LC_ALL=C sort | sed "s/\\\\/\\\\\\\\/g; s/\"/\\\\\"/g; s/^/$tab\"/; s/\$/\",/"
}

# the include directories of a compiler listing
includes() {
	awk '/^#include <\.\.\.> search starts here:/ { on = 1; next }
	     /^End of search list\./ { on = 0 }
	     on && /^ / && !/framework directory/ { sub(/^ +/, ""); print }' "$1" \
	    | sed "s/\\\\/\\\\\\\\/g; s/\"/\\\\\"/g; s/^/$tab\"/; s/\$/\",/"
}

# the name of a target in cparse from the macros of its compiler: the
# architecture, and the environment for Windows, macOS and WebAssembly
arch_of() {
	ptr=$(sed -n 's/^#define __SIZEOF_POINTER__ //p' "$1")
	has() {
		grep -Eq "^#define $2( |\$)" "$1"
	}
	if has "$1" __x86_64__; then
		base=x86_64
	elif has "$1" __i386__; then
		base=i386
	elif has "$1" __aarch64__; then
		base=aarch64
	elif has "$1" __arm__; then
		base=arm
	elif has "$1" __riscv && [ "$ptr" = 8 ]; then
		base=riscv64
	elif has "$1" __riscv && [ "$ptr" = 4 ]; then
		base=riscv32
	elif has "$1" __powerpc64__ && has "$1" __LITTLE_ENDIAN__; then
		base=ppc64le
	elif has "$1" __powerpc64__; then
		base=ppc64
	elif has "$1" __s390x__; then
		base=s390x
	elif has "$1" __loongarch64; then
		base=loongarch64
	elif has "$1" __wasm32__; then
		base=wasm32
	elif has "$1" __wasm64__; then
		base=wasm64
	elif has "$1" __mips__ && [ "$ptr" = 8 ]; then
		base=mips64
	elif has "$1" __mips__; then
		base=mips
	else
		echo unknown
		return
	fi
	if has "$1" __FILC__; then
		# Fil-C has x86-64 and AArch64 only
		case $base in
		x86_64|aarch64) echo "$base-filc" ;;
		*) echo unknown ;;
		esac
	elif has "$1" _WIN32 && { has "$1" __MINGW32__ || has "$1" __MINGW64__; }; then
		echo "$base-mingw"
	elif has "$1" _WIN32; then
		echo "$base-windows"
	elif has "$1" __APPLE__; then
		echo "$base-darwin"
	elif has "$1" __EMSCRIPTEN__; then
		echo "$base-emscripten"
	elif has "$1" __wasi__; then
		echo "$base-wasi"
	else
		echo "$base"
	fi
}

# set NAME COMPILER ARCH DEFINES INCLUDES
sets=""
n=0
emit_set() {
	cname=$1
	set_id=$2
	arch=$3
	defs=$4
	incs=$5

	echo "static const char *const cp_predef_defines_$set_id[] = {"
	defines "$defs"
	echo "};"
	echo "static const char *const cp_predef_includes_$set_id[] = {"
	if [ -n "$incs" ]; then
		includes "$incs"
	fi
	echo "	NULL"
	echo "};"
	echo
	sets="$sets	{ \"$cname\", \"$arch\", cp_predef_defines_$set_id,
	  ARRAY_SIZE(cp_predef_defines_$set_id),
	  cp_predef_includes_$set_id,
	  ARRAY_SIZE(cp_predef_includes_$set_id) - 1 },
"
	n=$((n + 1))
}

# the name of the compiler from its macros
compiler_of() {
	if grep -q '^#define __FILC__' "$1"; then
		echo filc
	elif grep -q '^#define __clang__' "$1"; then
		echo clang
	elif grep -q '^#define __GNUC__' "$1"; then
		echo gcc
	else
		echo unknown
	fi
}

echo "/* generated by gen-predefs.sh, do not edit */"
echo

case $mode in
host)
	for v in native m32; do
		opt=
		[ $v = m32 ] && opt=-m32
		# shellcheck disable=SC2086
		if ! $cc $opt -dM -E -x c /dev/null > "$tmp/$v.macros" 2> /dev/null; then
			continue
		fi
		# shellcheck disable=SC2086
		$cc $opt -E -v -x c /dev/null > /dev/null 2> "$tmp/$v.v" || true
		if [ $v = m32 ] && [ "$(sed -n 's/^#define __SIZEOF_POINTER__ //p' "$tmp/m32.macros")" = \
				     "$(sed -n 's/^#define __SIZEOF_POINTER__ //p' "$tmp/native.macros")" ]; then
			continue
		fi
		emit_set "$(compiler_of "$tmp/$v.macros")" "host_$v" "$(arch_of "$tmp/$v.macros")" \
			 "$tmp/$v.macros" "$tmp/$v.v"
	done
	;;
targets)
	for t in "$@"; do
		id=$(echo "$t" | tr -c 'A-Za-z0-9\n' _)
		macros="$tmp/$id.macros"
		if ! $cc --target="$t" -dM -E -x c /dev/null > "$macros" 2> /dev/null; then
			continue
		fi
		cname=$(compiler_of "$macros")
		# the names of the sets of clang stay as they are
		[ "$cname" = clang ] || id="${cname}_$id"
		emit_set "$cname" "$id" "$(arch_of "$macros")" "$macros" ""
	done
	;;
*)
	echo "unknown mode $mode" >&2
	exit 2
	;;
esac

echo "static const struct cp_predef_set cp_predef_sets_${name:-$mode}[] = {"
printf '%s' "$sets"
echo "	{ NULL, NULL, NULL, 0, NULL, 0 }"
echo "};"
